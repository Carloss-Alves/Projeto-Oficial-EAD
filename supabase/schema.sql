create extension if not exists pgcrypto;

create table if not exists public.notas_tecnicas (
  id bigint generated by default as identity primary key,
  numero integer not null unique,
  titulo text not null,
  descricao text not null default '',
  conteudo text not null default '',
  pdf_path text,
  pdf_url text,
  pdf_nome text,
  video_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.questoes (
  id bigint generated by default as identity primary key,
  nota_id bigint not null references public.notas_tecnicas(id) on delete cascade,
  pergunta text not null,
  alternativas jsonb not null default '["","","",""]'::jsonb,
  correta integer not null default 0 check (correta between 0 and 3),
  explicacao text not null default '',
  ordem integer not null default 0
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists questoes_nota_id_idx on public.questoes(nota_id);
create index if not exists questoes_ordem_idx on public.questoes(nota_id, ordem);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists notas_tecnicas_updated_at on public.notas_tecnicas;
create trigger notas_tecnicas_updated_at
before update on public.notas_tecnicas
for each row execute function public.set_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.admins
    where user_id = auth.uid()
  );
$$;

alter table public.notas_tecnicas enable row level security;
alter table public.questoes enable row level security;
alter table public.admins enable row level security;

drop policy if exists "notas_public_read" on public.notas_tecnicas;
create policy "notas_public_read"
on public.notas_tecnicas for select
to anon, authenticated
using (true);

drop policy if exists "notas_admin_insert" on public.notas_tecnicas;
create policy "notas_admin_insert"
on public.notas_tecnicas for insert
to authenticated
with check (public.is_admin());

drop policy if exists "notas_admin_update" on public.notas_tecnicas;
create policy "notas_admin_update"
on public.notas_tecnicas for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "notas_admin_delete" on public.notas_tecnicas;
create policy "notas_admin_delete"
on public.notas_tecnicas for delete
to authenticated
using (public.is_admin());

