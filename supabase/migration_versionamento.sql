-- -----------------------------------------------------------------
-- 1) notas_tecnicas.versao
-- -----------------------------------------------------------------
alter table public.notas_tecnicas
  add column if not exists versao integer not null default 1;

-- -----------------------------------------------------------------
-- 2) tabela progresso
-- -----------------------------------------------------------------
-- Cria a tabela apenas se ela ainda não existir no seu projeto.
-- Se já existir (como é o caso no ambiente de produção), este bloco
-- é ignorado e nenhuma coluna/linha existente é tocada.
create table if not exists public.progresso (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nota_id bigint not null references public.notas_tecnicas(id) on delete cascade,
  nome text not null default '',
  data_realizacao date,
  status text not null default 'em_andamento',
  acertos integer not null default 0,
  total_questoes integer not null default 0,
  nota numeric not null default 0,
  tempo_segundos integer not null default 0,
  versao_concluida integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Caso a tabela já existisse sem estas colunas, adiciona sem apagar
-- nada do que já está lá.
alter table public.progresso
  add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.progresso
  add column if not exists versao_concluida integer;

alter table public.progresso
  add column if not exists nome text not null default '';

alter table public.progresso
  add column if not exists data_realizacao date;

alter table public.progresso
  add column if not exists status text not null default 'em_andamento';

alter table public.progresso
  add column if not exists acertos integer not null default 0;

alter table public.progresso
  add column if not exists total_questoes integer not null default 0;

alter table public.progresso
  add column if not exists nota numeric not null default 0;

alter table public.progresso
  add column if not exists tempo_segundos integer not null default 0;

create index if not exists progresso_user_id_idx on public.progresso(user_id);
create index if not exists progresso_nota_id_idx on public.progresso(nota_id);

-- -----------------------------------------------------------------
-- 3) constraint de unicidade (user_id, nota_id)
-- -----------------------------------------------------------------
-- Adiciona a constraint somente se ela ainda não existir, com esse
-- nome ou com as mesmas colunas — nunca remove a constraint atual.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'progresso_user_id_nota_id_key'
  ) then
    alter table public.progresso
      add constraint progresso_user_id_nota_id_key unique (user_id, nota_id);
  end if;
end $$;

-- -----------------------------------------------------------------
-- 4) updated_at automático (reaproveita a função já usada em
--    notas_tecnicas; não altera nada se já existir)
-- -----------------------------------------------------------------
drop trigger if exists progresso_updated_at on public.progresso;
create trigger progresso_updated_at
before update on public.progresso
for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------
-- 5) RLS
-- -----------------------------------------------------------------
-- IMPORTANTE: a leitura pública (anon + authenticated) precisa
-- continuar liberada porque o Apps Script de sincronização com o
-- Google Sheets consulta a tabela `progresso` usando a chave anon,
-- sem sessão de usuário — se restringirmos o select por user_id, a
-- planilha para de sincronizar.
alter table public.progresso enable row level security;

drop policy if exists "progresso_public_read" on public.progresso;
create policy "progresso_public_read"
on public.progresso for select
to anon, authenticated
using (true);

-- Cada participante só pode criar/alterar o próprio progresso.
drop policy if exists "progresso_owner_insert" on public.progresso;
create policy "progresso_owner_insert"
on public.progresso for insert
to authenticated
with check (user_id = auth.uid());

drop policy if exists "progresso_owner_update" on public.progresso;
create policy "progresso_owner_update"
on public.progresso for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

